/**
 * 隐形字符清理：粘贴进笔记的正文里常混入肉眼看不见、但会污染摘要与搜索的字符。
 *
 * ## 为什么要单独一个文件
 *
 * `markdownPlainText` 的职责是「Markdown → 纯文本」；这一份是「不可见字符 → 干净文本」。
 * 两者目的不同，且这份清单**必须与 Rust 侧 `repo/note.rs::search` 用的一致**
 * —— 一端清、一端不清，搜索结果与摘要对不上，又是一次「两处真相」。
 *
 * ## ⚠️ 一条字符分三类处理，不是「一律换成空格」
 *
 * 判据是**「这个字符显示上占不占宽度」**：
 *
 * | 类 | 处理 | 理由 |
 * |---|---|---|
 * | ① 有可见宽度（NBSP、各类 Unicode 空格、全角空格、换行/段分隔符） | → **换成普通空格** | 它本来就是空白，只是宽度不同。删掉会让两个词真的贴在一起，产出「缺了间隔的伪连字」——而那个间隔在原文里**存在过** |
 * | ② 不可见的零宽类（ZWSP / ZWNJ / LRM / RLM / WJ / BOM） | → **删掉** | 显示上不占任何宽度，删掉完全不改变可见文本；换成空格是**凭空往文本里注入一个空格** |
 * | ③ 软连字符 `U+00AD` | → **删掉** | 同 ② |
 *
 * ⚠️ **第一版把 ① ② 一律换成空格，错了。** 症状：网页最常见的 `U+200B`
 * （防断词零宽空格）把单词劈开 —— `discuss<ZWSP>ion` → `discuss ion`、
 * `第<ZWSP>3` → `第 3`、中文的 `发<ZWSP>布计划` → `发 布计划`。
 * 用户看到的是「应用在正文里插了空格」，而正文一个字都没被改过。
 * 是 `markdown.test.mjs` 里那条链接用例先红才发现的 —— 它恰好让
 * 零宽字符出现在不该有空格的位置上。
 *
 * ## 与 `markdownPlainText` 末尾 `\s+` 的重叠关系
 *
 * JS 的 `\s` 已含：`U+00A0 U+1680 U+2000–U+200A U+2028 U+2029 U+202F
 * U+205F U+3000 U+FEFF` —— 即本文件的 ① 类与 ② 类的 BOM。
 * 摘要路径**真正靠这份代码补上的**只有：`U+200B U+200C U+200E U+200F
 * U+2060 U+00AD`。
 * 发布说明里说的「网页空格」在摘要里其实早就是干净的 —— 真正的漏网在
 * **搜索命中**那侧（SQL `LIKE` 完全不认 `\s`，任何不可见字符都会打断一次搜索），
 * 见 `repo/note.rs::search`。
 *
 * 仍然把 `\s` 覆盖的那批也列进来：**纯函数不该假设调用方已经做过空白合并。**
 * 依赖「上游恰好清过」是隐式契约，换个人接一个新调用点就悄悄漏了。
 *
 * ## ⚠️ ZWJ（`U+200D`）刻意**不**清
 *
 * emoji 序列靠它组合：`👨‍👩‍👧` = 三个 emoji + 两个 ZWJ。删掉 emoji 就碎了，
 * 而 emoji 在笔记里很常见。ZWNJ（`U+200C`）则要清 —— 正文里它几乎只来自
 * 网页排版，且删掉不影响 emoji（emoji 用的是 ZWJ 不是 ZWNJ）。
 *
 * 这条取舍是有意的保守：若将来确有人靠 ZWNJ 做波斯语排版，症状是 emoji
 * 少一个连接点，比整段 emoji 碎掉轻得多。
 */

/**
 * ① **有可见宽度**的空白字符 → 换成普通空格。
 *
 * 这些字符本身就是空白（只是宽度/换行语义不同），显示上「占一格」。
 * **必须换成空格而不是删掉**：删掉会让两个词真的贴在一起 ——
 * `中文{NBSP}和` 若变 `中文和`，用户看到的是缺了间隔的「伪连字」，
 * 而原文那个间隔是**存在过的**。
 */
const SPACED = /[\u00A0\u1680\u2000\u2001\u2002\u2003\u2004\u2005\u2006\u2007\u2008\u2009\u200A\u2028\u2029\u202F\u205F\u3000]/g

/**
 * ② **不可见**的零宽字符 → 删掉。
 *
 * ⚠️ 这条与 ① 相反，理由是同一个：它们显示上**不占任何宽度**，所以删掉
 * 完全不改变可见文本；而换成空格反而是**凭空往文本里注入一个空格**。
 *
 * 踩过的坑：第一版把全部字符一律换成空格，于是网页里最常见的
 * `U+200B`（防断词零宽空格）把单词劈开 ——
 * `discuss{ZWSP}ion` → `discuss ion`、`第{ZWSP}3` → `第 3`。
 * 中文也一样：`发{ZWSP}布计划` → `发 布计划`。
 * 用户会以为是应用在正文里插了空格。
 */
const ZERO_WIDTH = /[\u200B\u200C\u200E\u200F\u2060\uFEFF]/g

/** ③ `U+00AD` 软连字符：不可见，删。（单独一条便于说明为何不在 ② 里） */
const SOFT_HYPHEN = /\u00AD/g

/**
 * 把不可见字符换成普通空格（软连字符例外，直接删）。
 *
 * ⚠️ 换成**空格**而不是空串：`中文\u00A0和`粘在一起后清理会得到「中文 和」，
 *   （原文是 NBSP 与普通空格的视觉对比，写成码位才说得清差别 ——
 *   直接贴 NBSP 在源码里看不出来，还会让 review 的人以为是排版问题删掉。）
 *   而用户复制出去时那两个字之间确实需要一个空格。删掉的话，摘要里会出现
 *   肉眼看不到、却确实缺了间隔的「伪连字」。
 */
export function stripInvisible(input: string): string {
  return input.replace(SPACED, ' ').replace(ZERO_WIDTH, '').replace(SOFT_HYPHEN, '')
}

/**
 * 文本里是否存在不可见字符。
 *
 * ⚠️ `INVISIBLE` 带 `/g`，有 `lastIndex` 状态：**必须复位**，否则同一段文本
 *   第二次调用会返回 false（漏报）。下面两行就是为此存在，不是多余。
 */
export function hasInvisible(input: string): boolean {
  SPACED.lastIndex = 0
  ZERO_WIDTH.lastIndex = 0
  SOFT_HYPHEN.lastIndex = 0
  const found =
    SPACED.test(input) || ZERO_WIDTH.test(input) || SOFT_HYPHEN.test(input)
  SPACED.lastIndex = 0
  ZERO_WIDTH.lastIndex = 0
  SOFT_HYPHEN.lastIndex = 0
  return found
}
