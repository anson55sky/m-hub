//! 出网客户端构造：区分「连自己服务器」与「第三方」两类。
//!
//! reqwest 默认会跟随系统 / 环境变量代理（`HTTP_PROXY` / `HTTPS_PROXY` / `ALL_PROXY`）。
//! 用户开着 Clash / v2rayN 时，这些变量常被写成 `http://127.0.0.1:10808`（多是 SOCKS 口），
//! 而我们自己的域名（国内 IP）经它转发时 TLS 握手直接失败——表现为「在线功能全挂，
//! 报错却看不出跟代理有关」。
//!
//! 因此约定：
//! - **连自己服务器**（登录 / 更新 / 市场 / 平台模型）的客户端一律**直连**，忽略系统 / 环境代理；
//! - **第三方**（用户自配的 AI 服务、天气等）保持 reqwest 默认——跟随系统代理，
//!   它们在外网、可能恰恰需要代理才能访问。

/// 「连自己服务器」的客户端构造器：强制直连，不走系统 / 环境代理。
pub fn direct() -> reqwest::ClientBuilder {
    reqwest::Client::builder().no_proxy()
}
